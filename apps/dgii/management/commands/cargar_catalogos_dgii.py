class Command(BaseCommand):
    help = "Carga los catálogos DGII (provincias, monedas, unidades, etc.)"

    @transaction.atomic
    def handle(self, *args, **options):
        self._cargar_provincias_municipios()
        self._cargar_unidades_medida()
        self._cargar_monedas()
        self._cargar_impuestos()
        self._cargar_formas_pago()
        self.stdout.write(self.style.SUCCESS("Catálogos DGII cargados exitosamente."))

    def _cargar_provincias_municipios(self):
        for codigo, (nombre, municipios) in PROVINCIAS_MUNICIPIOS.items():
            provincia, created = Provincia.objects.update_or_create(
                codigo=codigo, defaults={"nombre": nombre}
            )
            if created:
                self.stdout.write(f"  + Provincia: {nombre}")
            for cod_mun, nom_mun in municipios:
                Municipio.objects.update_or_create(
                    codigo=cod_mun,
                    defaults={"provincia": provincia, "nombre": nom_mun},
                )

    def _cargar_unidades_medida(self):
        for codigo, abrev, nombre in UNIDADES_MEDIDA:
            created = UnidadMedida.objects.update_or_create(
                codigo=codigo, defaults={"abreviatura": abrev, "nombre": nombre}
            )[1]

    def _cargar_monedas(self):
        for iso, nombre in MONEDAS:
            Moneda.objects.update_or_create(
                codigo_iso=iso, defaults={"nombre": nombre}
            )

    def _cargar_impuestos(self):
        for codigo, nombre, desc, tipo, tasa in IMPUESTOS_ADICIONALES:
            ImpuestoAdicional.objects.update_or_create(
                codigo=codigo,
                defaults={
                    "nombre": nombre,
                    "descripcion": desc,
                    "tipo": tipo,
                    "tasa": tasa,
                },
            )

    def _cargar_formas_pago(self):
        for codigo, nombre in FORMAS_PAGO:
            FormaPago.objects.update_or_create(
                codigo=codigo, defaults={"nombre": nombre}
            )
